@dataclass(frozen=True, slots=True)
class OperationTemplate:
    """One operation exactly transcribed from Appendix A.

    ``uses_n`` means the proposal writes the operation with ``(n)`` where the
    current project defines n as the ordinal Source->Target distance.
    ``argument`` stores proposal literals such as ``Navigation`` or the Unpack
    hint bundle.
    """

    operation: str
    uses_n: bool = False
    argument: str | None = None
    origin: str = RULE_PROPOSAL_DEFINED
    proposal_reference: str = APPENDIX_A_REFERENCE


@dataclass(frozen=True, slots=True)
class ResourceTypeTransition:
    source: str
    target: str
    operation: str
    origin: str = RULE_PROPOSAL_DEFINED
    proposal_reference: str = APPENDIX_B_REFERENCE

    @property
    def blocks_realization(self) -> bool:
        # Appendix B labels Drop() as "not convertible" (غیر قابل تبدیل).
        return self.operation == "Drop"


@dataclass(frozen=True, slots=True)
class InteractivityTypeTransition:
    source: str
    target: str
    operation: str
    origin: str = RULE_CONFIGURED


U = OperationTemplate("Unpack", argument="hints: text, voice, video, animation")
P = OperationTemplate("Pack", uses_n=True)
E = OperationTemplate("Expand", uses_n=True)
NOP = OperationTemplate("NOP")
SD_DOWN = OperationTemplate("sdDecrease", uses_n=True)
SD_UP = OperationTemplate("sdIncrease", uses_n=True)
COG_DOWN = OperationTemplate("Cognitive_Level_down", uses_n=True)
COG_UP = OperationTemplate("Cognitive_Level_up", uses_n=True)
HTML = OperationTemplate("Export2HTML")


def ADD(action: str) -> OperationTemplate:
    return OperationTemplate("Add_Actions", argument=action)


def REMOVE(action: str) -> OperationTemplate:
    return OperationTemplate("Remove_Actions", argument=action)


