# Appendix C is a full ordinal transition matrix. The action can be generated
# without storing all cells because each matrix exactly uses direction +
# ordinal distance. The fixed project definition of n matches those cells.
_APPENDIX_C_SCALES: dict[str, tuple[str, ...]] = {
    "interactivityLevel": ("Very Low", "Low", "Medium", "High", "Very High"),
    "semanticDensity": ("Very Low", "Low", "Medium", "High", "Very High"),
    # Appendix C labels difficulty positions very-low..very-high, while the
    # GenoLOM vocabulary used by this project is Very Easy..Very Difficult.
    # We map them by ordinal position; this vocabulary reconciliation is a
    # project operationalization, while diffIncrease/diffDecrease(n) itself is
    # proposal-defined.
    "difficulty": ("Very Easy", "Easy", "Medium", "Difficult", "Very Difficult"),
}
_APPENDIX_C_PREFIXES = {
    "interactivityLevel": "il",
    "semanticDensity": "sd",
    "difficulty": "diff",
}


def appendix_c_mutation_action(field_name: str, source: str, target: str) -> str:
    """Return the exact Appendix-C action label for an ordinal transition."""

    if field_name not in _APPENDIX_C_SCALES:
        raise KeyError(f"Appendix C has no ordinal matrix for {field_name!r}.")
    scale = _APPENDIX_C_SCALES[field_name]
    if source not in scale or target not in scale:
        raise ValueError(
            f"Values {source!r}->{target!r} are outside the {field_name} scale."
        )
    delta = scale.index(target) - scale.index(source)
    if delta == 0:
        return "NOP"
    direction = "Increase" if delta > 0 else "Decrease"
    return f"{_APPENDIX_C_PREFIXES[field_name]}{direction}({abs(delta)})"


