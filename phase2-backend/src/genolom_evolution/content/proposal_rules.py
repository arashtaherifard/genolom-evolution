@dataclass(frozen=True, slots=True)
class ProposalRuleSet:
    """Authoritative proposal rules used by Milestone 4.

    Defaults are transcribed from proposal Appendices A-C. Configurable maps are
    still supported for controlled experiments, but the scientific default is
    no longer empty or guessed.
    """

    content_operations: Mapping[
        str, Mapping[str, tuple[OperationTemplate, ...]]
    ] = field(
        default_factory=lambda: {
            resource_type: dict(row)
            for resource_type, row in APPENDIX_A_CONTENT_OPERATIONS.items()
        }
    )
    resource_type_transitions: Mapping[
        tuple[str, str], ResourceTypeTransition
    ] = field(default_factory=_default_resource_type_transitions)
    interactivity_type_transitions: Mapping[
        tuple[str, str], InteractivityTypeTransition
    ] = field(default_factory=dict)
    # Implementation capability, not a proposal rule. Text-only Phase-2 V1 does
    # not pretend it has produced actual multimedia/interactive artifacts.
    unsupported_resource_types: frozenset[str] = frozenset(
        {"Simulation", "Video Clip", "Slide", "Authoring Tool"}
    )

    def content_operations_for(
        self, source_resource_type: str, action_family: str
    ) -> tuple[OperationTemplate, ...] | None:
        row = self.content_operations.get(source_resource_type)
        if row is None:
            return None
        return row.get(action_family)

    def resource_type_rule(
        self, source: str, target: str
    ) -> ResourceTypeTransition | None:
        return self.resource_type_transitions.get((source, target))

    def interactivity_type_rule(
        self, source: str, target: str
    ) -> InteractivityTypeTransition | None:
        return self.interactivity_type_transitions.get((source, target))


